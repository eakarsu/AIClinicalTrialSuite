randomizationRouter.post('/schemes', async (req, res) => {
  try {
    const { scheme_id, trial, block_size, arms, strata, category_schema, seed } = req.body;
    if (!scheme_id) return res.status(400).json({ error: 'scheme_id is required' });
    const armList = Array.isArray(arms) && arms.length >= 2 ? arms : [{ name: 'Active', ratio: 1 }, { name: 'Placebo', ratio: 1 }];
    const ratioSum = armList.reduce((s, a) => s + (a.ratio || 1), 0);
    const bs = Number(block_size) || ratioSum * 2;
    if (bs % ratioSum !== 0) {
      return res.status(400).json({ error: `block_size (${bs}) must be a multiple of the allocation-ratio sum (${ratioSum})` });
    }
    const r = await pool.query(
      `INSERT INTO randomization_schemes (scheme_id, trial, method, block_size, arms, strata, category_schema, seed)
       VALUES ($1,$2,'permuted-block',$3,$4,$5,$6,$7) RETURNING *`,
      [scheme_id, trial || null, bs, JSON.stringify(armList),
       JSON.stringify(Array.isArray(strata) ? strata : []),
       JSON.stringify(Array.isArray(category_schema) ? category_schema : []),
       seed || `${scheme_id}-${Date.now()}`]
    );
    res.status(201).json(r.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

