/* ============================================================
   ROUTER 6 — Form FDA 1572 generator  (/api/form-1572)
   Deterministic DRAFT assembly from existing records. Marked DRAFT:
   a real 1572 requires wet/e-signature and regulatory review.
   ============================================================ */
const form1572Router = express.Router();

form1572Router.post('/generate', async (req, res) => {
  try {
    const { investigator_id, trial } = req.body;
    if (!investigator_id) return res.status(400).json({ error: 'investigator_id is required' });
    const inv = await pool.query('SELECT * FROM investigators WHERE investigator_id=$1', [investigator_id]);
    if (inv.rows.length === 0) return res.status(404).json({ error: `Investigator ${investigator_id} not found` });
    const investigator = inv.rows[0];

    const site = investigator.site
      ? (await pool.query('SELECT * FROM sites WHERE site_id=$1', [investigator.site])).rows[0] || null
      : null;
    const trialRow = trial
      ? (await pool.query('SELECT * FROM trials WHERE trial_id=$1', [trial])).rows[0] || null
      : null;
    const subInvestigators = investigator.site
      ? (await pool.query(
          `SELECT entry_id, staff_name, staff_role, delegated_tasks FROM delegation_log_entries
           WHERE site=$1 AND status='active' ORDER BY staff_name`, [investigator.site])).rows
      : [];

    res.json({
      form: 'FDA-1572 (Statement of Investigator)',
      status: 'DRAFT — requires investigator signature and regulatory review before use',
      generated_at: new Date().toISOString(),
      section_1_investigator: {
        name: investigator.name,
        title: investigator.title,
        specialty: investigator.specialty,
        certifications: investigator.certifications,
      },
      section_2_education: 'Attach curriculum vitae (CV) — not stored in this system',
      section_3_facility: site ? { site_id: site.site_id, name: site.name, city: site.city, country: site.country } : null,
      section_4_clinical_lab: 'Attach laboratory certifications (CLIA/CAP) — not stored in this system',
      section_5_irb: 'See IRB workflow records for this site (/irb-workflows)',
      section_6_sub_investigators: subInvestigators,
      section_7_protocol: trialRow ? { trial_id: trialRow.trial_id, name: trialRow.name, phase: trialRow.phase, sponsor: trialRow.sponsor } : null,
      section_8_commitments: 'Standard Form 1572 commitments text applies (21 CFR 312.53).',
    });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

/* ============================================================
   ROUTERS 7 & 8 — Delegation log + Training records (CRUD)
   Same response shapes as the other CRUD modules (bare array on
   list, row objects elsewhere) so CrudTable just works.
   ============================================================ */
function crudRouter(table, idField, columns) {
  const router = express.Router();
  router.get('/', async (req, res) => {
    try {
      const r = await pool.query(`SELECT * FROM ${table} ORDER BY id DESC`);
      res.json(r.rows);
    } catch (err) { res.status(500).json({ error: err.message }); }
  });
  router.post('/', async (req, res) => {
    try {
      const vals = columns.map(c => req.body[c] ?? null);
      const params = columns.map((_, i) => `$${i + 1}`).join(',');
      const r = await pool.query(
        `INSERT INTO ${table} (${columns.join(',')}) VALUES (${params}) RETURNING *`, vals);
      res.status(201).json(r.rows[0]);
    } catch (err) { res.status(500).json({ error: err.message }); }
  });
  router.put('/:id', async (req, res) => {
    try {
      const sets = columns.map((c, i) => `${c}=$${i + 1}`).join(', ');
      const vals = columns.map(c => req.body[c] ?? null);
      const r = await pool.query(
        `UPDATE ${table} SET ${sets}, updated_at=NOW() WHERE id=$${columns.length + 1} RETURNING *`,
        [...vals, req.params.id]);
      if (r.rows.length === 0) return res.status(404).json({ error: 'Not found' });
      res.json(r.rows[0]);
    } catch (err) { res.status(500).json({ error: err.message }); }
  });
  router.delete('/:id', async (req, res) => {
    try {
      const r = await pool.query(`DELETE FROM ${table} WHERE id=$1 RETURNING id`, [req.params.id]);
      if (r.rows.length === 0) return res.status(404).json({ error: 'Not found' });
      res.json({ deleted: true });
    } catch (err) { res.status(500).json({ error: err.message }); }
  });
  return router;
}

