const dsmbRouter = express.Router();

dsmbRouter.post('/packet', async (req, res) => {
  try {
    const { trial } = req.body;
    if (!trial) return res.status(400).json({ error: 'trial is required' });
    const t = await pool.query('SELECT * FROM trials WHERE trial_id=$1', [trial]);
    if (t.rows.length === 0) return res.status(404).json({ error: `Trial ${trial} not found` });

    const [enrollBySite, enrollByArm, aeSeverity, aeSerious, deviations, queries, milestones] = await Promise.all([
      pool.query(`SELECT site, COUNT(*)::int AS n FROM patients WHERE trial=$1 GROUP BY site ORDER BY site`, [trial]),
      pool.query(`SELECT COALESCE(arm,'(unassigned)') AS arm, COUNT(*)::int AS n FROM patients WHERE trial=$1 GROUP BY arm ORDER BY arm`, [trial]),
      pool.query(`SELECT severity, COUNT(*)::int AS n FROM adverse_events WHERE trial=$1 GROUP BY severity`, [trial]),
      pool.query(`SELECT COUNT(*)::int AS n FROM adverse_events WHERE trial=$1 AND serious=TRUE`, [trial]),
      pool.query(`SELECT type, status, COUNT(*)::int AS n FROM deviations WHERE trial=$1 GROUP BY type, status`, [trial]),
      pool.query(`SELECT status, COUNT(*)::int AS n FROM queries WHERE trial=$1 GROUP BY status`, [trial]),
      pool.query(`SELECT milestone_id, name, target_date, actual_date, status FROM milestones WHERE trial=$1 ORDER BY target_date`, [trial]),
    ]);

    const packet = {
      trial: t.rows[0],
      generated_at: new Date().toISOString(),
      enrollment: { by_site: enrollBySite.rows, by_arm: enrollByArm.rows },
      safety: { ae_by_severity: aeSeverity.rows, serious_ae_count: aeSerious.rows[0].n },
      conduct: { deviations: deviations.rows, queries: queries.rows },
      milestones: milestones.rows,
    };

    // ADVISORY AI executive summary over the aggregates only (no PHI).
    let summary = null;
    try {
      const r = await callOpenRouter(
        SYSTEM_PROMPT,
        `Write a DSMB open-session executive summary for this trial data. Return STRICT JSON: {"summary": string, "signals": [string], "recommended_focus_areas": [string]}.\nDATA: ${JSON.stringify({ trial: packet.trial.trial_id, indication: packet.trial.indication, phase: packet.trial.phase, ...packet.enrollment, ...packet.safety, ...packet.conduct })}`
      );
      summary = safeJsonParse(r, { summary: typeof r === 'string' ? r : '' });
    } catch (e) { summary = { summary: '', error: `AI narrative unavailable: ${e.message}` }; }

    const out = withAdvisory({ packet, executive_summary: summary });
    await persist('dsmb-packet', req.body, out);
    res.json(out);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

/* ============================================================
   ROUTER 4 — Enrollment forecast  (/api/enrollment-forecast)
   Deterministic accrual projection from patients.enrolled_at,
   plus ADVISORY AI narrative.
   ============================================================ */
const forecastRouter = express.Router();

forecastRouter.post('/run', async (req, res) => {
  try {
    const { trial, target_n } = req.body;
    if (!trial) return res.status(400).json({ error: 'trial is required' });
    const target = Number(target_n) || 0;

    const r = await pool.query(
      `SELECT date_trunc('month', enrolled_at) AS month, COUNT(*)::int AS n
       FROM patients WHERE trial=$1 AND enrolled_at IS NOT NULL
       GROUP BY 1 ORDER BY 1`, [trial]);
    const monthly = r.rows.map(x => ({ month: String(x.month.toISOString()).slice(0, 7), n: x.n }));
    const enrolled = monthly.reduce((s, m) => s + m.n, 0);

    // Rate = mean of the most recent 3 accrual months (or all, if fewer).
    const recent = monthly.slice(-3);
    const rate = recent.length ? recent.reduce((s, m) => s + m.n, 0) / recent.length : 0;
    const remaining = Math.max(0, target - enrolled);
    const monthsToTarget = rate > 0 && remaining > 0 ? Math.ceil(remaining / rate) : (remaining === 0 ? 0 : null);

    const projection = {
      trial, enrolled, target_n: target || null,
      monthly_accrual: monthly,
      recent_rate_per_month: Number(rate.toFixed(2)),
      remaining, months_to_target: monthsToTarget,
      projected_completion: monthsToTarget !== null && target
        ? new Date(Date.now() + monthsToTarget * 30.44 * 24 * 3600 * 1000).toISOString().slice(0, 10)
        : null,
      method: 'mean of last 3 accrual months, linear projection',
    };

    let narrative = null;
    try {
      const ai = await callOpenRouter(
        SYSTEM_PROMPT,
        `Given this enrollment projection, return STRICT JSON {"narrative": string, "risks": [string], "accelerators": [string]}.\nDATA: ${JSON.stringify(projection)}`
      );
      narrative = safeJsonParse(ai, { narrative: typeof ai === 'string' ? ai : '' });
    } catch (e) { narrative = { narrative: '', error: `AI narrative unavailable: ${e.message}` }; }

    const out = withAdvisory({ projection, narrative });
    await persist('enrollment-forecast', req.body, out);
    res.json(out);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

