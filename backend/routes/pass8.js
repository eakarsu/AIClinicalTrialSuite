const sdtmRouter = express.Router();

const SDTM_DOMAINS = {
  DM: { label: 'Demographics',      source: 'patients' },
  AE: { label: 'Adverse Events',    source: 'adverse_events' },
  DV: { label: 'Protocol Deviations', source: 'deviations' },
};

sdtmRouter.get('/domains', (req, res) => {
  res.json(Object.entries(SDTM_DOMAINS).map(([code, d]) => ({ domain: code, ...d })));
});

async function sdtmRows(domain, trial) {
  const where = trial ? ' WHERE trial = $1' : '';
  const params = trial ? [trial] : [];
  if (domain === 'DM') {
    const r = await pool.query(`SELECT * FROM patients${where} ORDER BY trial, patient_id`, params);
    return r.rows.map((p, i) => ({
      STUDYID: p.trial, DOMAIN: 'DM',
      USUBJID: `${p.trial}-${p.patient_id}`, SUBJID: p.patient_id,
      SITEID: p.site, ARM: p.arm || '', ARMCD: (p.arm || '').replace(/[^A-Za-z0-9]/g, '').slice(0, 8).toUpperCase(),
      RFSTDTC: p.enrolled_at ? String(p.enrolled_at.toISOString()).slice(0, 10) : '',
      DMSEQ: i + 1,
    }));
  }
  if (domain === 'AE') {
    const r = await pool.query(`SELECT * FROM adverse_events${where} ORDER BY trial, event_id`, params);
    return r.rows.map((a, i) => ({
      STUDYID: a.trial, DOMAIN: 'AE',
      USUBJID: `${a.trial}-${a.patient}`, AESEQ: i + 1,
      AETERM: a.term, AESEV: (a.severity || '').toUpperCase(),
      AESER: a.serious ? 'Y' : 'N',
      AESTDTC: a.reported_at ? String(a.reported_at.toISOString()).slice(0, 10) : '',
      AEOUT: (a.outcome || '').toUpperCase(),
    }));
  }
  if (domain === 'DV') {
    const r = await pool.query(`SELECT * FROM deviations${where} ORDER BY trial, deviation_id`, params);
    return r.rows.map((d, i) => ({
      STUDYID: d.trial, DOMAIN: 'DV',
      USUBJID: `${d.trial}-SITE:${d.site}`, DVSEQ: i + 1,
      DVTERM: d.description || '', DVCAT: (d.type || '').toUpperCase(),
      DVSTATUS: (d.status || '').toUpperCase(),
    }));
  }
  throw new Error(`Unsupported domain ${domain}`);
}

sdtmRouter.get('/:domain', async (req, res) => {
  try {
    const domain = String(req.params.domain || '').toUpperCase();
    if (!SDTM_DOMAINS[domain]) return res.status(404).json({ error: `Unknown domain ${domain}. Supported: ${Object.keys(SDTM_DOMAINS).join(', ')}` });
    const rows = await sdtmRows(domain, req.query.trial || null);
    if ((req.query.format || '').toLowerCase() === 'csv') {
      const cols = rows.length ? Object.keys(rows[0]) : [];
      res.setHeader('Content-Type', 'text/csv');
      res.setHeader('Content-Disposition', `attachment; filename="${domain}.csv"`);
      return res.send(toCsv(rows, cols));
    }
    res.json({ domain, sdtm_shaped: true, cdisc_validated: false, count: rows.length, rows });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

