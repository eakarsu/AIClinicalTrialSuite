// Deterministic 32-bit PRNG (mulberry32) seeded from a string hash,
// so block shuffles are reproducible from (scheme.seed, stratum, block_no).
function hashString(s) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Build the (deterministic) permuted block for a given block number.
// The block contains each arm repeated proportionally to its ratio,
// scaled to block_size, then Fisher-Yates shuffled with the seeded PRNG.
function permutedBlock(scheme, stratum, blockNo) {
  const arms = scheme.arms;
  const ratioSum = arms.reduce((s, a) => s + (a.ratio || 1), 0);
  const perUnit = Math.max(1, Math.floor(scheme.block_size / ratioSum));
  const block = [];
  for (const a of arms) for (let i = 0; i < (a.ratio || 1) * perUnit; i++) block.push(a.name);
  const rand = mulberry32(hashString(`${scheme.seed}|${stratum}|${blockNo}`));
  for (let i = block.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [block[i], block[j]] = [block[j], block[i]];
  }
  return block;
}

