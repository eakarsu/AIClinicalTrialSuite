// Randomize one subject. Position within stratum decides block number and
// slot; the block itself is regenerated deterministically — nothing secret
// is stored, and the full schedule can be re-derived for audit.
randomizationRouter.post('/schemes/:schemeId/assign', async (req, res) => {
  const client = await pool.connect();
  try {
    const { subject_id, stratum } = req.body;
    if (!subject_id) return res.status(400).json({ error: 'subject_id is required' });
    await client.query('BEGIN');
    const s = await client.query('SELECT * FROM randomization_schemes WHERE scheme_id=$1 FOR UPDATE', [req.params.schemeId]);
    if (s.rows.length === 0) { await client.query('ROLLBACK'); return res.status(404).json({ error: 'Scheme not found' }); }
    const scheme = s.rows[0];
    if (scheme.status !== 'active') { await client.query('ROLLBACK'); return res.status(400).json({ error: `Scheme is ${scheme.status}` }); }
    const strata = scheme.strata || [];
    const st = stratum || '';
    if (strata.length > 0 && !strata.includes(st)) {
      await client.query('ROLLBACK');
      return res.status(400).json({ error: `stratum must be one of: ${strata.join(', ')}` });
    }
    const dup = await client.query(
      'SELECT 1 FROM randomization_assignments WHERE scheme=$1 AND subject_id=$2', [scheme.scheme_id, subject_id]);
    if (dup.rows.length > 0) { await client.query('ROLLBACK'); return res.status(409).json({ error: `Subject ${subject_id} already randomized in this scheme` }); }

    const cnt = await client.query(
      'SELECT COUNT(*)::int AS n FROM randomization_assignments WHERE scheme=$1 AND stratum=$2', [scheme.scheme_id, st]);
    const pos = cnt.rows[0].n;                       // 0-based position within stratum
    const block = permutedBlock(scheme, st, Math.floor(pos / scheme.block_size));
    const arm = block[pos % scheme.block_size];

    const ins = await client.query(
      `INSERT INTO randomization_assignments (scheme, subject_id, stratum, arm, block_no, position, assigned_by)
       VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *`,
      [scheme.scheme_id, subject_id, st, arm, Math.floor(pos / scheme.block_size), pos % scheme.block_size, req.user?.email || null]
    );
    await client.query('COMMIT');
    res.status(201).json(ins.rows[0]);
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    res.status(500).json({ error: err.message });
  } finally { client.release(); }
});

randomizationRouter.post('/irt/dispense', async (req, res) => {
  const client = await pool.connect();
  try {
    const { scheme_id, subject_id, site, assigned_by, notes } = req.body || {};
    if (!scheme_id || !subject_id) return res.status(400).json({ error: 'scheme_id and subject_id are required' });
    await client.query('BEGIN');
    const a = await client.query(
      `SELECT a.*, s.trial FROM randomization_assignments a
       JOIN randomization_schemes s ON s.scheme_id=a.scheme
       WHERE a.scheme=$1 AND a.subject_id=$2
       FOR UPDATE`,
      [scheme_id, subject_id]
    );
    if (a.rows.length === 0) {
      await client.query('ROLLBACK');
      return res.status(404).json({ error: `No randomization assignment found for ${subject_id} in ${scheme_id}` });
    }
    const assignment = a.rows[0];
    const existing = await client.query('SELECT * FROM irt_dispenses WHERE scheme=$1 AND subject_id=$2', [scheme_id, subject_id]);
    if (existing.rows.length > 0) {
      await client.query('ROLLBACK');
      return res.status(409).json({ error: 'Subject already has an IRT dispense record', dispense: existing.rows[0] });
    }
    const kit = await client.query(
      `SELECT * FROM irt_kits
       WHERE trial=$1 AND arm=$2 AND status='available'
         AND ($3::text IS NULL OR site=$3)
       ORDER BY expiry_date ASC NULLS LAST, kit_id ASC
       LIMIT 1 FOR UPDATE`,
      [assignment.trial, assignment.arm, site || null]
    );
    if (kit.rows.length === 0) {
      await client.query('ROLLBACK');
      return res.status(409).json({ error: `No available kit for trial ${assignment.trial}, arm ${assignment.arm}${site ? `, site ${site}` : ''}` });
    }
    const selectedKit = kit.rows[0];
    await client.query(
      `UPDATE irt_kits
       SET status='assigned', assigned_subject=$1, assigned_at=NOW(), updated_at=NOW()
       WHERE id=$2`,
      [subject_id, selectedKit.id]
    );
    const dispenseId = `DSP-${Date.now()}-${Math.random().toString(36).slice(2, 7).toUpperCase()}`;
    const d = await client.query(
      `INSERT INTO irt_dispenses (dispense_id, scheme, trial, subject_id, arm, kit_id, site, dispensed_by, notes)
       VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9) RETURNING *`,
      [dispenseId, scheme_id, assignment.trial, subject_id, assignment.arm, selectedKit.kit_id, selectedKit.site, assigned_by || req.user?.email || null, notes || null]
    );
    await client.query('COMMIT');
    res.status(201).json({ assignment, kit: { ...selectedKit, status: 'assigned', assigned_subject: subject_id }, dispense: d.rows[0] });
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    res.status(500).json({ error: err.message });
  } finally {
    client.release();
  }
});

