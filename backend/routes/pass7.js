irbRouter.post('/:id/transition', async (req, res) => {
  try {
    const { to_state, reason } = req.body || {};
    if (!to_state) return res.status(400).json({ error: '`to_state` required' });

    const wf = await pool.query('SELECT * FROM irb_workflows WHERE id=$1', [req.params.id]);
    if (wf.rows.length === 0) return res.status(404).json({ error: 'Workflow not found' });
    const current = wf.rows[0];
    const allowed = IRB_TRANSITIONS[current.state] || [];
    if (!allowed.includes(to_state)) {
      return res.status(400).json({
        error: `Illegal transition: ${current.state} -> ${to_state}. Allowed: ${allowed.join(', ') || '(terminal)'}.`,
      });
    }
    const stamp = to_state === 'approved' || to_state === 'continuing_review' ? 'NOW()' : null;
    const updated = await pool.query(
      `UPDATE irb_workflows
         SET state=$1, last_review_at=${stamp ? stamp : 'last_review_at'}, updated_at=NOW()
       WHERE id=$2 RETURNING *`,
      [to_state, req.params.id]
    );
    await pool.query(
      `INSERT INTO irb_workflow_transitions (workflow_id, from_state, to_state, actor, reason)
       VALUES ($1,$2,$3,$4,$5)`,
      [current.workflow_id, current.state, to_state, req.user?.email || 'system', reason || null]
    );
    res.json({ workflow: updated.rows[0], previous_state: current.state, new_state: to_state });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

