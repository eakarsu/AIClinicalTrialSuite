/* ============================================================
   ROUTER 2 — comparable trial finder (DB-side, MECHANICAL)
   Mounted at /api/comparable-trials
   ============================================================ */
const comparableRouter = express.Router();

comparableRouter.post('/find', async (req, res) => {
  try {
    const body = req.body || {};
    const indication = (body.indication || '').trim();
    const phase = (body.phase || '').trim();
    const limit = Math.min(50, Math.max(1, parseInt(body.limit) || 10));

    if (!indication && !phase) {
      return res.status(400).json({ error: 'At least one of `indication` or `phase` is required.' });
    }

    // Tokenize the indication for a loose match — split on non-word chars, drop
    // very short tokens, and search for any token via ILIKE.
    const tokens = indication
      .split(/[^a-zA-Z0-9]+/)
      .map((t) => t.trim())
      .filter((t) => t.length >= 3);

    const where = [];
    const params = [];
    let i = 1;
    if (tokens.length > 0) {
      const ors = tokens.map(() => `indication ILIKE $${i++}`);
      where.push('(' + ors.join(' OR ') + ')');
      tokens.forEach((t) => params.push('%' + t + '%'));
    }
    if (phase) {
      where.push(`phase ILIKE $${i++}`);
      params.push('%' + phase + '%');
    }
    const whereSql = where.length ? 'WHERE ' + where.join(' AND ') : '';

    const r = await pool.query(
      `SELECT trial_id, name, indication, phase, status, sponsor, start_date
         FROM trials
         ${whereSql}
         ORDER BY start_date DESC NULLS LAST
         LIMIT ${limit}`,
      params
    );

    // Rough similarity score: count how many tokens hit the indication, +1 if phase matches.
    const scored = r.rows.map((row) => {
      const ind = (row.indication || '').toLowerCase();
      const tokenHits = tokens.reduce((s, t) => s + (ind.includes(t.toLowerCase()) ? 1 : 0), 0);
      const phaseHit = phase && row.phase && row.phase.toLowerCase() === phase.toLowerCase() ? 1 : 0;
      const denom = Math.max(1, tokens.length + (phase ? 1 : 0));
      return {
        ...row,
        similarity_score: +((tokenHits + phaseHit) / denom).toFixed(3),
      };
    });
    scored.sort((a, b) => b.similarity_score - a.similarity_score);

    res.json({
      source: 'internal_trials_table',
      query: { indication, phase, tokens, limit },
      result_count: scored.length,
      results: scored,
      notes: [
        'Internal DB match only. ClinicalTrials.gov / EudraCT / CTIS / ICTRP search requires NEEDS-CREDS integration (see /api/integrations/ctgov/search).',
      ],
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

/* ============================================================
   ROUTER 3 — protocol version-graph
   Mounted at /api/protocols-graph
   (Cannot mount at /api/protocols/* because protocols.js owns that
    prefix with a writeGate; this is a read-only view so we keep
    it separate and open to any authenticated user.)
   ============================================================ */
const protocolGraphRouter = express.Router();

protocolGraphRouter.get('/by-trial/:trialId', async (req, res) => {
  try {
    const trialId = req.params.trialId;
    const protocols = await pool.query(
      `SELECT id, protocol_id, trial, version, status, approved_by, approved_at, created_at, updated_at
         FROM protocols WHERE trial=$1 ORDER BY created_at ASC`,
      [trialId]
    );
    const amendments = await pool.query(
      `SELECT id, amendment_id, trial, version, summary, status, approved_at, created_at
         FROM amendments WHERE trial=$1 ORDER BY created_at ASC`,
      [trialId]
    );

    // Nodes: each protocol + each amendment.
    // Edges: protocols chained in version order; amendments attach to the
    // protocol whose version they reference (best-effort string match), else
    // to the most-recent protocol prior to the amendment's created_at.
    const nodes = [];
    protocols.rows.forEach((p) =>
      nodes.push({
        node_id: `P:${p.protocol_id}`,
        type: 'protocol',
        label: `${p.protocol_id} v${p.version || '?'}`,
        version: p.version,
        status: p.status,
        approved_at: p.approved_at,
        created_at: p.created_at,
      })
    );
    amendments.rows.forEach((a) =>
      nodes.push({
        node_id: `A:${a.amendment_id}`,
        type: 'amendment',
        label: `${a.amendment_id} v${a.version || '?'}`,
        version: a.version,
        status: a.status,
        approved_at: a.approved_at,
        created_at: a.created_at,
        summary: a.summary,
      })
    );

    const edges = [];
    for (let i = 1; i < protocols.rows.length; i++) {
      edges.push({
        from: `P:${protocols.rows[i - 1].protocol_id}`,
        to: `P:${protocols.rows[i].protocol_id}`,
        type: 'supersedes',
      });
    }
    amendments.rows.forEach((a) => {
      // try exact version match
      let parent = protocols.rows.find((p) => p.version && a.version && p.version === a.version);
      if (!parent) {
        // most-recent protocol before the amendment
        parent = [...protocols.rows]
          .filter((p) => new Date(p.created_at) <= new Date(a.created_at))
          .pop();
      }
      if (!parent && protocols.rows.length > 0) parent = protocols.rows[protocols.rows.length - 1];
      if (parent) {
        edges.push({
          from: `P:${parent.protocol_id}`,
          to: `A:${a.amendment_id}`,
          type: 'amended_by',
        });
      }
    });

    res.json({
      trial: trialId,
      node_count: nodes.length,
      edge_count: edges.length,
      nodes,
      edges,
      protocols: protocols.rows,
      amendments: amendments.rows,
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// Simple text-diff between two protocol versions (by protocol_id pair).
// We don't store the protocol body, so we diff metadata fields + any
// amendments whose version sits between v_from and v_to.
protocolGraphRouter.get('/diff', async (req, res) => {
  try {
    const fromId = req.query.from;
    const toId = req.query.to;
    if (!fromId || !toId) {
      return res.status(400).json({ error: 'Both `from` and `to` query params required (protocol_id values).' });
    }
    const r = await pool.query('SELECT * FROM protocols WHERE protocol_id IN ($1,$2)', [fromId, toId]);
    const fromRow = r.rows.find((p) => p.protocol_id === fromId);
    const toRow = r.rows.find((p) => p.protocol_id === toId);
    if (!fromRow || !toRow) return res.status(404).json({ error: 'One or both protocols not found' });

    const fields = ['trial', 'version', 'status', 'approved_by', 'approved_at'];
    const changes = fields
      .map((f) => ({ field: f, from: fromRow[f], to: toRow[f] }))
      .filter((c) => String(c.from) !== String(c.to));

    // Bracket amendments between the two protocol creation timestamps.
    const amendments = await pool.query(
      `SELECT amendment_id, version, summary, status, created_at FROM amendments
         WHERE trial=$1 AND created_at BETWEEN $2 AND $3 ORDER BY created_at ASC`,
      [fromRow.trial, fromRow.created_at, toRow.created_at]
    );

    res.json({
      from: fromRow,
      to: toRow,
      metadata_changes: changes,
      intervening_amendments: amendments.rows,
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

