/* ---------- MECHANICAL: power-calc explainer ---------- */
/* Deterministic: explain assumptions (alpha, beta, MDE, SD, allocation).
   We do NOT pretend to be a power-analysis package — we surface the
   walk-through and an n-per-arm estimate using a textbook normal-approx
   formula so the explanation has a concrete number. */
function zForAlpha(alpha, twoSided = true) {
  // crude inverse normal — covers common 0.05/0.025/0.01/0.005 cases
  const a = twoSided ? alpha / 2 : alpha;
  if (a <= 0.0005) return 3.291;
  if (a <= 0.001)  return 3.090;
  if (a <= 0.005)  return 2.576;
  if (a <= 0.01)   return 2.326;
  if (a <= 0.025)  return 1.960;
  if (a <= 0.05)   return 1.645;
  return 1.282;
}
function zForPower(power) {
  if (power >= 0.99) return 2.326;
  if (power >= 0.95) return 1.645;
  if (power >= 0.9)  return 1.282;
  if (power >= 0.85) return 1.036;
  if (power >= 0.8)  return 0.842;
  if (power >= 0.7)  return 0.524;
  return 0.253;
}
aiRouter.post('/power-calc-explain', async (req, res) => {
  try {
    const body = req.body || {};
    const alpha = Number(body.alpha) || 0.05;
    const power = Number(body.power) || 0.8;
    const sd = Number(body.sd) || 1.0;
    const mde = Number(body.mde) || 0.5;
    const dropout = Number(body.dropout_rate) || 0.15;
    const twoSided = body.two_sided !== false;

    const za = zForAlpha(alpha, twoSided);
    const zb = zForPower(power);
    // continuous outcome, two-arm 1:1, normal approx
    const nPerArmEvaluable = Math.ceil(2 * Math.pow((za + zb) * sd / mde, 2));
    const nPerArmEnrolled = Math.ceil(nPerArmEvaluable / Math.max(0.05, 1 - dropout));
    const totalN = nPerArmEnrolled * 2;

    const deterministic = {
      inputs: { alpha, power, sd, mde, dropout_rate: dropout, two_sided: twoSided },
      derived: {
        z_alpha: Number(za.toFixed(3)),
        z_beta: Number(zb.toFixed(3)),
        n_per_arm_evaluable: nPerArmEvaluable,
        n_per_arm_enrolled: nPerArmEnrolled,
        total_n_enrolled: totalN,
      },
      formula: 'n_per_arm = 2 * ((z_{alpha/2} + z_{beta}) * SD / MDE)^2 (continuous outcome, two-arm 1:1, normal approximation)',
      assumptions_walkthrough: [
        `Significance level (alpha): ${alpha}${twoSided ? ' two-sided' : ' one-sided'} -> z_alpha = ${za.toFixed(3)}`,
        `Target power (1 - beta): ${power} -> z_beta = ${zb.toFixed(3)}`,
        `Pooled SD on the primary endpoint scale: ${sd}`,
        `Minimum detectable effect (MDE) on the primary endpoint scale: ${mde}`,
        `Drop-out inflation: ${(dropout * 100).toFixed(0)}% -> enrolled n_per_arm = ceil(evaluable / (1 - dropout))`,
        '1:1 allocation between treatment and control assumed. For unequal allocation, multiply by (1 + 1/k)/2 with k = ratio.',
      ],
      caveats: [
        'This is a normal-approximation estimate for a continuous outcome. It is NOT a substitute for a biostatistician-validated power analysis package (e.g. PASS, nQuery, EAST, SAS PROC POWER).',
        'For survival, count, time-to-event, non-inferiority, or group-sequential designs, the formula above does not apply and a specialist tool MUST be used.',
        'Effect size assumptions should be defended with literature or a pilot dataset before being used in a protocol.',
      ],
    };

    let narrative = null;
    try {
      const sys = `${SYSTEM_PROMPT} Return JSON: { "narrative": string, "key_caveats": [string] }. Focus on EXPLAINING the inputs and the resulting n; do NOT invent numbers.`;
      const user = `Explain the assumptions and resulting sample size below to a non-statistician trial sponsor. Be concrete; reference each input.
Deterministic calc result: ${JSON.stringify(deterministic)}`;
      const r = await callOpenRouter(sys, user);
      narrative = safeJsonParse(r, { narrative: typeof r === 'string' ? r : '', key_caveats: [] });
    } catch (e) {
      narrative = { narrative: '(AI narrative unavailable: ' + e.message + ')', key_caveats: [] };
    }

    const result = { ...deterministic, ai_narrative: narrative };
    await persist('power-calc-explain', body, result);
    res.json(result);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

/* ---------- MECHANICAL: patient burden estimator ---------- */
/* Pure structured calc + optional AI narrative.
   Inputs: visits[{name, procedures[{name, minutes}], travel_minutes}].
   Output: total minutes, hours, day-count, intensity tag, plus narrative. */
aiRouter.post('/patient-burden', async (req, res) => {
  try {
    const body = req.body || {};
    const visits = Array.isArray(body.visits) ? body.visits : [];
    let totalProcedureMin = 0;
    let totalTravelMin = 0;
    let totalProcedures = 0;
    const perVisit = visits.map((v, idx) => {
      const procs = Array.isArray(v.procedures) ? v.procedures : [];
      const procMin = procs.reduce((s, p) => s + (Number(p.minutes) || 0), 0);
      const travelMin = (Number(v.travel_minutes) || 0) * 2; // round trip
      totalProcedureMin += procMin;
      totalTravelMin += travelMin;
      totalProcedures += procs.length;
      return {
        index: idx,
        name: v.name || `Visit ${idx + 1}`,
        procedure_count: procs.length,
        procedure_minutes: procMin,
        travel_minutes_round_trip: travelMin,
        total_minutes: procMin + travelMin,
      };
    });

    const totalMin = totalProcedureMin + totalTravelMin;
    const totalHours = +(totalMin / 60).toFixed(2);
    const equivalentFullDays = +(totalMin / 480).toFixed(2); // 8-hour days
    let intensity = 'Low';
    if (totalHours > 80) intensity = 'Very High';
    else if (totalHours > 40) intensity = 'High';
    else if (totalHours > 16) intensity = 'Moderate';

    const deterministic = {
      visit_count: visits.length,
      total_procedure_count: totalProcedures,
      total_procedure_minutes: totalProcedureMin,
      total_travel_minutes: totalTravelMin,
      total_minutes: totalMin,
      total_hours: totalHours,
      equivalent_full_8h_days: equivalentFullDays,
      intensity_tag: intensity,
      per_visit: perVisit,
    };

    let narrative = null;
    try {
      const sys = `${SYSTEM_PROMPT} Return JSON: { "patient_facing_summary": string, "burden_reduction_suggestions": [string] }. Plain language, no PHI, no medical advice.`;
      const user = `Summarise patient burden for this trial schedule (one paragraph, plain language) and suggest 3-5 burden-reduction ideas (decentralised visits, home health, telehealth, combined procedure days). Use ONLY the numbers below.
${JSON.stringify(deterministic)}`;
      const r = await callOpenRouter(sys, user);
      narrative = safeJsonParse(r, { patient_facing_summary: typeof r === 'string' ? r : '', burden_reduction_suggestions: [] });
    } catch (e) {
      narrative = { patient_facing_summary: '(AI narrative unavailable: ' + e.message + ')', burden_reduction_suggestions: [] };
    }

    const result = { ...deterministic, ai_narrative: narrative };
    await persist('patient-burden', body, result);
    res.json(result);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

